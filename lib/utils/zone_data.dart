  /// Retorna la lista de polígonos que corresponden a un nombre de zona
  static List<List<LatLng>> getPolygonsForZone(String zoneName) {
    final subNames = operationalSubPolygons[zoneName];
    if (subNames != null && subNames.isNotEmpty) {
      final list = <List<LatLng>>[];
      for (final s in subNames) {
        final p = polygons[s];
        if (p != null) list.add(p);
      }
      return list;
    }
    final direct = polygons[zoneName];
    if (direct != null) return [direct];
    return [];
  }

  /// Retorna el nombre de la zona a la que pertenece un punto, o null si está fuera de todas
  static String? getZoneForPoint(LatLng point) {
    for (final entry in polygons.entries) {
      if (isPointInPolygon(point, entry.value)) {
        return entry.key;
      }
    }
    return null;
  }

  /// Verifica si un punto cae dentro de alguna de las zonas en la lista de nombres de zona proporcionados
  static bool isPointInAnyZone(LatLng point, Iterable<String> zoneNames) {
    if (zoneNames.isEmpty) return false;
    final normalizedTargets = zoneNames.map(normalizeZoneName).toSet();

    for (final targetName in zoneNames) {
      final polyList = getPolygonsForZone(targetName);
      for (final p in polyList) {
        if (isPointInPolygon(point, p)) return true;
      }
    }

    for (final entry in polygons.entries) {
      final normKey = normalizeZoneName(entry.key);
      if (normalizedTargets.contains(normKey)) {
        if (isPointInPolygon(point, entry.value)) {
          return true;
        }
      }
    }
    return false;
  }

  /// Normaliza el nombre de una zona eliminando tildes y pasando a minúsculas
  static String normalizeZoneName(String name) {
    return name
        .toLowerCase()
        .replaceAll('á', 'a')
        .replaceAll('é', 'e')
        .replaceAll('í', 'i')
        .replaceAll('ó', 'o')
        .replaceAll('ú', 'u')
        .replaceAll('ñ', 'n')
        .trim();
  }

  /// Verifica si un punto (latitud, longitud) se encuentra dentro de un polígono (Ray Casting)
  static bool isPointInPolygon(LatLng point, List<LatLng> polygon) {
    if (polygon.length < 3) return false;

    // Chequeo rápido de Bounding Box para máximo rendimiento
    double minLat = polygon[0].latitude;
    double maxLat = polygon[0].latitude;
    double minLng = polygon[0].longitude;
    double maxLng = polygon[0].longitude;

    for (int i = 1; i < polygon.length; i++) {
      final p = polygon[i];
      if (p.latitude < minLat) minLat = p.latitude;
      if (p.latitude > maxLat) maxLat = p.latitude;
      if (p.longitude < minLng) minLng = p.longitude;
      if (p.longitude > maxLng) maxLng = p.longitude;
    }

    if (point.latitude < minLat ||
        point.latitude > maxLat ||
        point.longitude < minLng ||
        point.longitude > maxLng) {
      return false;
    }

    // Algoritmo de Ray Casting (Even-Odd Rule)
    bool inside = false;
    final double x = point.longitude;
    final double y = point.latitude;

    for (int i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
      final double xi = polygon[i].longitude;
      final double yi = polygon[i].latitude;
      final double xj = polygon[j].longitude;
      final double yj = polygon[j].latitude;

      final bool intersect = ((yi > y) != (yj > y)) &&
          (x < (xj - xi) * (y - yi) / (yj - yi) + xi);
      if (intersect) {
        inside = !inside;
      }
    }
    return inside;
  }

  /// Retorna el nombre de la zona a la que pertenece un punto, o null si está fuera de todas
  static String? getZoneForPoint(LatLng point) {
    for (final entry in polygons.entries) {
      if (isPointInPolygon(point, entry.value)) {
        return entry.key;
      }
    }
    return null;
  }

  /// Verifica si un punto cae dentro de alguna de las zonas en la lista de nombres de zona proporcionados
  static bool isPointInAnyZone(LatLng point, Iterable<String> zoneNames) {
    if (zoneNames.isEmpty) return false;
    final normalizedTargets = zoneNames.map(normalizeZoneName).toSet();

    for (final entry in polygons.entries) {
      final normKey = normalizeZoneName(entry.key);
      if (normalizedTargets.contains(normKey)) {
        if (isPointInPolygon(point, entry.value)) {
          return true;
        }
      }
    }
    return false;
  }
